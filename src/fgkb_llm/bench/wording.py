"""Alternative wordings of deep items (prompt robustness, P16).

Every deep item is asked in three wordings; the gold answer, the knowledge base patch and the queried
property do not change, only the surface text:

* **W1** — the original template: "Is it true that <h>? Answer yes, no or undetermined."
* **W2** — rule-based variation: a direct yes/no question by subject--verb inversion ("Does a lone wolf
  deal with a crime?", "¿Comercia un lobo solitario con un delito?"; when inversion is not safe, the frame
  "Is it correct that <h>?" / "¿Es correcto afirmar que <h>?", whose frame words are not KB events) and,
  for nouns whose alternative lemma has been approved by a FunGramKB expert
  (``data/extension/w2_synonyms.json``), another lemma of the same concept ("a crime" -> "an offence").
  The lexicon groups near-synonyms and hyponymic lexicalisations under one concept (amphetamine /
  methamphetamine), so alternatives are used only after approval. Articles are regenerated by the
  verbaliser, Spanish substitutions must keep the gender (the predicate agrees with it) and every
  substitution is checked with the shared linker.
* **W3** — free paraphrase by an LLM that is not one of the evaluated models
  (``scripts/make_wordings.py --paraphrase``), filtered by automatic checks (``check_paraphrase``) and
  audited by a human on a sample.

The proposition always stays inside the question sentence, so the neuro-symbolic pipelines see the
same kind of input in all wordings; the answer instruction is always the original one, so answer
parsing does not depend on the wording.
"""

from __future__ import annotations

import copy
import hashlib
import re

from ..corel import nlg
from ..kb.model import KnowledgeBase
from .schema import Item

INSTRUCTION = {"en": "Answer yes, no or undetermined.", "es": "Responde sí, no o indeterminado."}
W1_FRAME = {"en": "Is it true that ", "es": "¿Es cierto que "}
W2_FRAME = {"en": "Is it correct that ", "es": "¿Es correcto afirmar que "}
NEGATION = {"en": re.compile(r"\b(not|never|no|n't)\b", re.IGNORECASE), "es": re.compile(r"\b(no|nunca|jamás|ningún|ninguna)\b", re.IGNORECASE)}


def split_item_text(question: str, lang: str) -> tuple[str, str] | None:
    """(background sentences, proposition h without final '?') of a W1 question, or None."""
    q = question.strip()
    instr = INSTRUCTION[lang]
    if not q.endswith(instr):
        return None
    q = q[: -len(instr)].strip()
    frame = W1_FRAME[lang]
    i = q.rfind(frame)
    if i < 0 or not q.endswith("?"):
        return None
    return q[:i].strip(), q[i + len(frame):-1].strip()


def join_item_text(background: str, question_sentence: str, lang: str) -> str:
    bg = (background.strip() + " ") if background.strip() else ""
    return f"{bg}{question_sentence.strip()} {INSTRUCTION[lang]}"


# ---------------------------------------------------------------------------------------- W2
def _with_first_lemma(kb: KnowledgeBase, cid: str, lang: str, lemma: str) -> KnowledgeBase:
    """Shallow KB view in which `lemma` is the first lemma of `cid` in `lang` (so the verbaliser's NP
    functions use it, with the right article and gender)."""
    view = copy.copy(kb)
    first = [lu for lu in kb.lexicon if lu.concept == cid and lu.lang == lang and lu.lemma == lemma]
    ids = {id(lu) for lu in first}
    view.lexicon = first + [lu for lu in kb.lexicon if id(lu) not in ids]
    return view


def candidate_alternative(kb: KnowledgeBase, cid: str, lang: str) -> str | None:
    lemmas = kb.lemmas(cid, lang)
    if len(lemmas) < 2:
        return None
    cands = [lem for lem in lemmas[1:] if lemmas[0] not in lem.split() and lem.lower() != lemmas[0].lower()]
    if not cands:
        return None
    # deterministic choice per concept and language
    k = int(hashlib.sha1(f"{cid}|{lang}".encode()).hexdigest(), 16) % len(cands)
    return cands[k]


def _np(kb: KnowledgeBase, cid: str, lang: str) -> str:
    return nlg._en_np(kb, cid) if lang == "en" else nlg._es_np(kb, cid)[0]


def substitute_nouns(kb: KnowledgeBase, linker, text: str, lang: str,
                     approved: dict[str, dict[str, str]] | None = None) -> tuple[str, list[tuple[str, str, str]]]:
    """Replace singular, unquantified NPs of entities by another lemma of the same concept.

    ``approved`` maps concept -> language -> alternative lemma; without it nothing is substituted.
    Returns the new text and the substitutions made (concept, old NP, new NP). A substitution is kept
    only if the linker still finds the concept in the new text (and finds no concept that was not there).
    """
    if not approved:
        return text, []
    before = set(linker.concepts(text, lang))
    subs = []
    for cid in list(dict.fromkeys(linker.concepts(text, lang))):
        con = kb.concepts.get(cid)
        if con is None or con.semantic_type != "entity":
            continue
        alt = (approved.get(cid) or {}).get(lang)
        if not alt or alt not in kb.lemmas(cid, lang):
            continue
        view = _with_first_lemma(kb, cid, lang, alt)
        if lang == "es" and nlg.es_feminine(kb.label(cid, lang)) != nlg.es_feminine(alt):
            continue  # "la marihuana es ingerido": the predicate agrees with the original gender
        old, new = _np(kb, cid, lang), _np(view, cid, lang)
        pat = re.compile(rf"(?<![\w-]){re.escape(old)}(?![\w-])", re.IGNORECASE)
        if old == new or not pat.search(text):
            continue

        def repl(m, new=new):
            return new[:1].upper() + new[1:] if m.group(0)[:1].isupper() else new

        cand = pat.sub(repl, text)
        after = set(linker.concepts(cand, lang))
        if cid in after and after <= before | {cid}:
            text = cand
            subs.append((cid, old, new))
    return text, subs


def _en_base(verb: str) -> str:
    irregular = {s3: base for base, (s3, _) in nlg.EN_IRREG.items() if " " not in base}
    if verb in irregular:
        return irregular[verb]
    if verb.endswith("ies") and len(verb) > 4:
        return verb[:-3] + "y"
    if verb.endswith(("sses", "shes", "ches", "xes", "zes", "oes")):
        return verb[:-2]
    return verb[:-1] if verb.endswith("s") and not verb.endswith("ss") else verb


def _subject_end(item: Item, kb: KnowledgeBase, linker, h: str) -> int | None:
    """End offset of the subject NP at the start of the proposition h (the queried concept)."""
    focus = item.focus_concepts[0] if item.focus_concepts else None
    for m in linker.link(h, item.lang):
        if m.concept == focus and m.start <= 6:
            return m.end
    for w in pseudowords(item, kb):
        m = re.match(rf"^\s*(?:(?:a|an|un|una)\s+)?{re.escape(w)}\b", h, re.IGNORECASE)
        if m:
            return m.end()
    return None


def invert(item: Item, kb: KnowledgeBase, linker, h: str) -> str | None:
    """Direct yes/no question from the declarative proposition h, or None when inversion is not safe."""
    end = _subject_end(item, kb, linker, h)
    if end is None:
        return None
    subj, rest = h[:end].strip(), h[end:].strip().split()
    if not rest:
        return None
    if item.lang == "en":
        v = rest[0].lower()
        if v in ("not", "never", "does", "do", "can", "will") or (len(rest) > 1 and rest[1] in ("not", "never")):
            return None
        if v in ("is", "are"):
            return f"{v.capitalize()} {subj} {' '.join(rest[1:])}?"
        if not v.endswith("s"):
            return None
        return f"Does {subj} {_en_base(v)} {' '.join(rest[1:])}".strip() + "?"
    v = rest[0].lower()
    if v in ("no", "nunca", "jamás"):
        return None
    verb, tail = (" ".join(rest[:2]), rest[2:]) if v == "se" and len(rest) > 1 else (rest[0], rest[1:])
    if v in ("es", "está") and len(tail) == 1:  # copula + adjective: "¿Es pequeña una bomba?"
        return f"¿{verb[:1].upper()}{verb[1:]} {tail[0]} {subj}?"
    return f"¿{verb[:1].upper()}{verb[1:]} {subj} {' '.join(tail)}".strip() + "?"


def w2_item(kb: KnowledgeBase, linker, item: Item, approved: dict | None = None) -> Item | None:
    parts = split_item_text(item.question, item.lang)
    if parts is None:
        return None
    bg, h = parts
    bg2, subs_bg = substitute_nouns(kb, linker, bg, item.lang, approved) if bg else ("", [])
    h2, subs_h = substitute_nouns(kb, linker, h, item.lang, approved)
    q = invert(item, kb, linker, h2)
    form = "inversion" if q else "frame"
    if q is None:
        q = f"{W2_FRAME[item.lang]}{h2}?"
    return derived(item, "w2", join_item_text(bg2, q, item.lang), w2_form=form,
                   substitutions=[list(s) for s in subs_bg + subs_h])


