PARAPHRASE_PROMPT = {
    "en": (
        "Rewrite the text below with different words and sentence structure while keeping EXACTLY the same "
        "meaning. Rules: keep every made-up word (such as {pseudo}) exactly as written; keep negations; keep "
        "quantities such as 'many' or 'some'; the last sentence must remain a yes/no question about the same "
        "statement, with the same subject (what the question is about stays the grammatical subject); do not add information, explanations or an answer. Return exactly ONE rewritten version, "
        "with no alternatives, notes or comments.\n\n"
        "Text: {text}"
    ),
    "es": (
        "Reescribe el texto siguiente con otras palabras y otra estructura sintáctica manteniendo EXACTAMENTE "
        "el mismo significado. Reglas: conserva tal cual toda palabra inventada (como {pseudo}); conserva las "
        "negaciones; conserva cuantificadores como 'muchos' o 'algunos'; la última oración debe seguir siendo "
        "una pregunta de sí o no sobre la misma afirmación y con el mismo sujeto (aquello por lo que se pregunta "
        "sigue siendo el sujeto gramatical); no añadas información, explicaciones ni la "
        "respuesta. Devuelve UNA sola versión reescrita, sin alternativas, notas ni comentarios.\n\nTexto: {text}"
    ),
}


def paraphrase_source(item: Item) -> str | None:
    """The text given to the paraphraser: background + question sentence, without the instruction."""
    parts = split_item_text(item.question, item.lang)
    if parts is None:
        return None
    bg, h = parts
    return (bg + " " if bg else "") + f"{W1_FRAME[item.lang]}{h}?"


def pseudowords(item: Item, kb: KnowledgeBase) -> list[str]:
    """Made-up words of the item (concepts of its KB patch that are not in the base KB)."""
    patch = item.meta.get("kb_patch") or {}
    words = []
    for cid, spec in (patch.get("concepts") or {}).items():
        if cid in kb.concepts or not isinstance(spec, dict):
            continue
        lemma = (spec.get("lemmas") or {}).get(item.lang)
        words.append(lemma or cid.strip("$+#").rsplit("_", 1)[0].lower())
    return [w for w in dict.fromkeys(words) if w]


_NOTE = re.compile(r"^\s*(\(|\*|note|nota|alternativ|or:|o:|versi[oó]n|option|opci[oó]n|elige|choose)", re.IGNORECASE)


def clean_paraphrase(text: str) -> str:
    """First version only: instruction-tuned paraphrasers often append alternatives or notes after a blank
    line ("(Note: ...)", "Alternatively: ..."). Labels such as "Text:" / "Texto:" are removed."""
    t = (text or "").strip()
    first = re.split(r"\n\s*\n", t, maxsplit=1)[0]
    lines = [ln for ln in first.splitlines() if ln.strip() and not _NOTE.match(ln)]
    out = " ".join(ln.strip() for ln in lines)
    out = re.sub(r"^(rewritten text|text|texto reescrito|texto)\s*:\s*", "", out, flags=re.IGNORECASE)
    return out.strip().strip('"').strip("«»").strip()


def check_paraphrase(source: str, para: str, item: Item, kb: KnowledgeBase, linker) -> str | None:
    """None if the paraphrase passes the automatic checks, else the reason it is rejected."""
    lang = item.lang
    p = clean_paraphrase(para)
    if not p or len(p) > 3 * len(source) + 40:
        return "empty or too long"
    if not p.endswith("?"):
        return "last sentence is not a question"
    if re.search(r"\b(yes|no|undetermined|sí|indeterminado)\s*[.!]?\s*$", p.rstrip("?"), re.IGNORECASE) and \
            re.search(r"\b(answer|respuesta|responde)\b", p, re.IGNORECASE):
        return "contains an answer"
    for w in pseudowords(item, kb):
        if w.lower() not in p.lower():
            return f"pseudoword '{w}' lost"
    if len(NEGATION[lang].findall(source)) != len(NEGATION[lang].findall(p)):
        return "negation changed"
    n_src = len(re.findall(r"[.?!](\s|$)", source))
    n_par = len(re.findall(r"[.?!](\s|$)", p))
    if n_par != n_src:
        return "number of sentences changed"
    focus = item.focus_concepts[0] if item.focus_concepts else None
    if focus and focus in kb.concepts and focus not in linker.concepts(p, lang):
        return "focus concept not found by the linker"
    # generic -> existential: "A drolnen is a kind of ecstasy" -> "Some drolnens are ..." (human audit, 7 Oct 2026)
    if len(_EXISTENTIAL[lang].findall(p)) > len(_EXISTENTIAL[lang].findall(source)):
        return "generic statement made existential"
    return None


_EXISTENTIAL = {"en": re.compile(r"(?:^|[.?!]\s+)(?:some|certain)\b", re.IGNORECASE),
                "es": re.compile(r"(?:^|[.?!¿]\s*)(?:algun[oa]s|ciert[oa]s)\b", re.IGNORECASE)}


def subject_changed(para: str, item: Item, kb: KnowledgeBase, linker) -> bool:
    """True when the question's grammatical subject is no longer the queried concept ("Is alcohol ingested by
    a human?" -> "Does a person consume alcohol?"). Not a rejection criterion: the human audit judged most
    of these paraphrases equivalent (voice alternation); the flag lets the analysis report them separately,
    since the neuro-symbolic pipelines query the subject's closure."""
    p = clean_paraphrase(para)
    question = re.findall(r"[^.?!]*\?", p)
    q = question[-1] if question else p
    first = _first_entity(q, item, kb, linker)
    focus = item.focus_concepts[0] if item.focus_concepts else None
    return first is not None and first != focus


def _first_entity(text: str, item: Item, kb: KnowledgeBase, linker) -> str | None:
    """The first entity mentioned in a sentence: a pseudoword of the item or a linked entity concept."""
    hits = []
    for w in pseudowords(item, kb):
        m = re.search(rf"\b{re.escape(w)}", text, re.IGNORECASE)
        if m:
            hits.append((m.start(), item.focus_concepts[0] if item.focus_concepts else w))
    for mention in linker.link(text, item.lang):
        con = kb.concepts.get(mention.concept)
        if con is not None and con.semantic_type == "entity":
            hits.append((mention.start, mention.concept))
            break
    return min(hits)[1] if hits else None


def w3_item(item: Item, para: str, **meta) -> Item:
    return derived(item, "w3", join_item_text("", clean_paraphrase(para), item.lang), **meta)


# ---------------------------------------------------------------------------------------- common
def derived(item: Item, wording: str, question: str, **meta) -> Item:
    new = copy.deepcopy(item)
    new.id = f"{item.id}@{wording}"
    new.pair_id = f"{item.pair_id}@{wording}" if item.pair_id else None  # twins stay paired within a wording
    new.question = question
    new.meta = {**item.meta, "wording": wording, "base_id": item.id, **meta}
    return new
